/**
 * 国际化字符串资源系统
 * 
 * 该文件定义了应用程序的国际化字符串资源系统，采用函数式接口设计，
 * 支持多语言、动态参数和主题化字符串管理，为整个应用程序提供统一的文本资源管理。
 * 
 * 主要特性：
 * - 多语言支持：通过不同语言实现类（zhCN、enUS等）提供本地化文本
 * - 函数式接口：支持带参数的字符串格式化（如version、timeSeconds等）
 * - 分组管理：按功能模块（应用、侧边栏、头部、设置等）组织字符串
 * - 类型安全：使用Kotlin数据类确保字符串引用的安全性
 * 
 * 设计特点：
 * - 可扩展性：易于添加新的语言和地区支持
 * - 性能优化：使用CompositionLocalProvider实现高效的字符串传递
 * - 用户友好：提供直观的命名约定和分组结构
 * - 维护性：集中管理所有UI文本，便于翻译和维护
 * 
 * @see zhCN 中文语言实现
 * @see enUS 英文语言实现
 * @see stringsFor 字符串资源获取函数
 * @see LocalStrings 字符串资源CompositionLocal
 */

